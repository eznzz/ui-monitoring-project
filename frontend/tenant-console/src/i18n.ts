export type TranslationKey = keyof typeof messages.ru;
export function tr(lang: UILanguage,key: TranslationKey):string {
 const group: Record<string,string> = messages[lang as keyof typeof messages] ?? messages.en;
 return group[key] || messages.en[key] || messages.ru[key];
}
export function resolveUILanguage(raw?: string): UILanguage {
 const normalized=(raw||"").toLowerCase().split(/[-_]/)[0];
 return normalized==="ru"||normalized==="el" ? normalized : "en";
}
